import type { ArmorKind } from './equipment';
import type { StatId } from './glossary';
import type { SchoolId } from './spells';

export interface Feature {
  level: number;
  name: string;
  text: string;
}

/** A list the class picks from as it levels up (Savage Arsenal, Underhanded Abilities…). */
export interface ChoiceDef {
  id: string;
  name: string;
  /** levels at which one more is chosen */
  at: number[];
  options: { id: string; name: string; text: string; req?: string }[];
}

export interface SubclassDef {
  id: string;
  name: string;
  en: string;
  text?: string;
  features: Feature[];
  /** story-based subclass, taken when the story demands it */
  story?: boolean;
}

/** which weapons a class is proficient with (without proficiency a weapon can't crit) */
export type WeaponProf = 'str' | 'dex' | 'martial' | 'blades-staves-wands' | 'blades-wands' | 'str-wands' | 'dex-wands' | 'staves-wands' | 'melee';

export interface ClassMagic {
  schools: SchoolId[];
  /** the mana pool: (KEY×3)+LVL, WIL+LVL, or none (the Shadowmancer steals power) */
  mana: { stat: StatId; times: number } | null;
  /** level at which each tier unlocks: tiers[1] = level for tier 1, … */
  tiers: number[];
  /** from which level the class knows its cantrips */
  cantripsAt: number;
  /** Songweaver: one more school of the player's choice */
  extraSchool?: boolean;
}

export interface ClassDef {
  id: string;
  name: string;
  en: string;
  tagline: string;
  complexity: number;
  keyStats: [StatId, StatId];
  secondaryStats: [StatId, StatId];
  hitDie: number;
  startHp: number;
  saves: { adv: StatId; dis: StatId };
  armorText: string;
  armor: ArmorKind[];
  weaponsText: string;
  weapons: WeaponProf;
  /** starting gear by id (weapons, armour, gear) */
  gear: string[];
  features: Feature[];
  choices: ChoiceDef[];
  subclasses: SubclassDef[];
  magic?: ClassMagic;
  /** class resources for the sheet's trackers (Fury Dice, Combat Dice…), by level */
  resources?: (level: number, stats: Record<StatId, number>) => { id: string; name: string; max: number; die?: string; reset: 'safe' | 'encounter' | 'day' }[];
}

